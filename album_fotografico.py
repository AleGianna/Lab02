def carica_da_file(file_path):
    """Carica le foto dal file,  creando un nuovo anno ogni volta che compare per la prima volta"""
    album = []
    f=open(file_path, "r")
    file=csv.reader(f)
    inte = next(file)
    for row in file:
        diz={}
        diz[inte[0]] = row[0]
        diz[inte[1]] = row[1]
        diz[inte[2]] = row[2]
        diz[inte[3]] = int(row[3])
        diz[inte[4]] = int(row[4])
        album.append(diz)
    f.close()
    return album

